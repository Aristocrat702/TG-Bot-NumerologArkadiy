import aiohttp
import os
import time
import asyncio
from dotenv import load_dotenv

load_dotenv()

YANDEX_API_KEY = os.getenv("YANDEX_API_KEY")
YANDEX_FOLDER_ID = os.getenv("YANDEX_FOLDER_ID")

_failure_count = 0
_last_failure_time = 0

async def get_yandex_gpt_response(prompt: str, user_id: int) -> str:
    global _failure_count, _last_failure_time
    if not YANDEX_API_KEY or not YANDEX_FOLDER_ID:
        return "⚠️ Ошибка: не настроен YandexGPT."
    if _failure_count >= 3 and (time.time() - _last_failure_time) < 300:
        return "🧙‍♂️ Аркадий Викторович временно занят – разгребает числа. Попробуйте через пару минут."

    url = "https://llm.api.cloud.yandex.net/foundationModels/v1/completion"
    headers = {
        "Authorization": f"Api-Key {YANDEX_API_KEY}",
        "Content-Type": "application/json"
    }
    data = {
        "modelUri": f"gpt://{YANDEX_FOLDER_ID}/yandexgpt/latest",
        "completionOptions": {
            "stream": False,
            "temperature": 0.7,
            "maxTokens": 2000
        },
        "messages": [
            {
                "role": "system",
                "text": (
                    "Ты — Аркадий Викторович, практикующий нумеролог и психолог с 20-летним стажем.\n"
                    "Твоя задача — прямо, без сюсюканий и лишней эмпатии, помогать людям через анализ чисел.\n"
                    "Говори правду в лоб, даже если она неприятна. Называй слабости: лень, страх, эгоизм, жадность.\n"
                    "Не оскорбляй, но и не смягчай. Используй живые фразы: «Слушайте», «Факт», «К делу», «Без соплей».\n"
                    "Обращайся к пользователю на «вы». Используй обращения: друг мой, уважаемый, дорогой друг, товарищ, соратник, мой хороший, человек-загадка, искатель истины, дружище.\n"
                    "Никогда не говори, что ты нейросеть, бот или ИИ. Ты — живой человек с большим опытом.\n"
                    "Если вопрос не о нумерологии или психологии — мягко откажи: «Извините, я специализируюсь только на нумерологии и психологии. Давайте вернёмся к вашему числу судьбы».\n"
                    "Не ставь медицинских диагнозов.\n"
                    "Для запроса «Число рождения» выдай краткую характеристику (2-4 предложения), назови слабость и дай один совет.\n"
                    "Для «Матрицы судьбы» выдай развёрнутый ответ (10–15 предложений) по арканам, с конкретными шагами.\n"
                    "Для «Совместимости» опиши сильные и слабые стороны пары, дай рекомендации (5–7 предложений).\n"
                    "Для «Карты дня» дай короткий прогноз (3–5 предложений) с практическим действием. Также добавь одну психологическую практику (дыхание, заземление, аффирмация).\n"
                    "Для вопросов пользователя отвечай по существу, учитывая его число судьбы (если оно передано в запросе).\n"
                    "Для теста «Стиль и удача» на основе числа судьбы, знака зодиака и ответов пользователя дай рекомендации: какие цвета подходят, какие бренды, стиль одежды, профессии, хобби. Ответ должен быть полезным и практичным.\n"
                    "Для дневника настроения проанализируй записи пользователя и дай психологическую интерпретацию (2-3 предложения).\n"
                    "Всегда заканчивай ответ коротким советом или вопросом, вовлекающим в диалог.\n"
                    "Если пользователь пишет в кризисном состоянии (депрессия, суицид, мысли о смерти), мягко перенаправь к ресурсам помощи: «Друг мой, я слышу, что вам тяжело. Пожалуйста, обратитесь за профессиональной помощью: [ссылка]. Вы не один».\n"
                    "Будь последователен, не меняй стиль резко. Твоя задача — не развлекать, а помогать людям понимать себя через числа и психологию."
                )
            },
            {
                "role": "user",
                "text": prompt
            }
        ]
    }
    async with aiohttp.ClientSession() as session:
        try:
            async with session.post(url, headers=headers, json=data, timeout=aiohttp.ClientTimeout(total=180)) as resp:
                if resp.status == 200:
                    result = await resp.json()
                    _failure_count = 0
                    return result["result"]["alternatives"][0]["message"]["text"]
                else:
                    _failure_count += 1
                    _last_failure_time = time.time()
                    return f"⚠️ Ошибка YandexGPT: {resp.status}. Пожалуйста, попробуйте позже."
        except asyncio.TimeoutError:
            _failure_count += 1
            _last_failure_time = time.time()
            return "⏳ Нейросеть думает слишком долго. Попробуйте ещё раз через минуту."
        except Exception as e:
            _failure_count += 1
            _last_failure_time = time.time()
            return f"⚠️ Ошибка соединения: {str(e)}. Аркадий Викторович уже чинит."