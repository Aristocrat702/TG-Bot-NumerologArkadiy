async def detect_gender_by_name(name: str) -> str:
    """
    Определяет пол по имени.
    Сначала проверяет по словарю, затем через YandexGPT.
    Возвращает 'male', 'female' или 'unknown'.
    """
    name_lower = name.lower().strip()
    first_name = name_lower.split()[0] if name_lower else ""
    if not first_name:
        return "unknown"
    
    # Проверка по словарю
    if first_name in MALE_NAMES:
        return "male"
    if first_name in FEMALE_NAMES:
        return "female"
    
    # Если словарь не помог – спрашиваем YandexGPT
    try:
        prompt = f"Определи пол человека по имени: {first_name}. Ответь только одним словом: 'male' или 'female'. Если не знаешь, ответь 'unknown'."
        response = await get_yandex_gpt_response(prompt, 0, function_name="gender_detection")
        if "male" in response.lower():
            return "male"
        elif "female" in response.lower():
            return "female"
        else:
            return "unknown"
    except:
        return "unknown"